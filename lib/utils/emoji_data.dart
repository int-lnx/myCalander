    items = items.where((item) => item.category == category);
  }

  if (query.trim().isEmpty) {
    return items.toList();
  }

  final lowerQuery = query.toLowerCase().trim();
  return items.where((item) {
    if (item.name.toLowerCase().contains(lowerQuery)) return true;
    for (var kw in item.keywords) {
      if (kw.toLowerCase().contains(lowerQuery)) return true;
    }
    return false;
  }).toList();
}
